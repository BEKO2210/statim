def _fill(text, fmt):
    if not fmt or "{" not in text:
        return text
    try:
        return text.format(**fmt)
    except (KeyError, IndexError, ValueError):
        return text


def instruction(kind, item_lang, rng, category=None, **fmt):
    """Return (text, language used). Item language 70% of the time, otherwise English."""
    lang = item_lang if item_lang in TEMPLATES and rng.random() < 0.70 else "en"
    bank = None
    if category and category in CATEGORY_TEMPLATES and kind in CATEGORY_TEMPLATES[category]:
        by_lang = CATEGORY_TEMPLATES[category][kind]
        bank = by_lang.get(lang) or by_lang.get("en")
    if not bank:
        bank = TEMPLATES[lang][kind]
    return _fill(rng.choice(bank), fmt), lang


def _squash(label):
    """A label without case and separators: registry.canon() turns "check-worthy" into "check worthy"
    and "nothate" into "not hate", while GLOSSES keeps the source's spelling."""
    return re.sub(r"[\s_./-]+", "", str(label).strip().lower())


def describe(category, label, lang):
    """Short description in ``lang`` for a fixed label, otherwise the humanised id."""
    key = str(label).strip().lower()
    gloss_lang = lang if lang in GLOSSES.get(category or "", {}) else "en"
    table = GLOSSES.get(category or "", {}).get(gloss_lang, {})
    if key in table:
        return table[key]
    squashed = {_squash(k): v for k, v in table.items()}
    if _squash(key) in squashed:
        return squashed[_squash(key)]
    if category == "language_id" and key in _LANG_NAMES:
        names = _LANG_NAMES[key]
        idx = LANGUAGES.index(lang) if lang in LANGUAGES else 0
        return names[idx]
    text = str(label).replace("_", " ").replace("-", " ")
    return " ".join(text.split())


def score_levels(category, lang, canonical):
    """Translate a known level scale. Unknown scales are returned unchanged."""
    if category == "relevance":
        category = "similarity"
    table = LEVELS.get(category, {}).get(lang if lang in LANGUAGES else "en")
    english = LEVELS.get(category, {}).get("en")
    if table and english and list(canonical) == list(english):
        return list(table)
    return list(canonical)


def aspect_name(name, lang):
    row = _ASPECTS.get(name)
    if not row:
        return name
    idx = LANGUAGES.index(lang) if lang in LANGUAGES else 0
    return row[idx]


def shuffle_choice(options, gold, rng):
    """Return shuffled options and a matching one-hot target."""
    options = list(options)
    order = list(range(len(options)))
    rng.shuffle(order)
    shuffled = [options[i] for i in order]
    return shuffled, [1.0 if i == gold else 0.0 for i in order]


def seeded(seed, *parts):
    """Stable RNG independent of Python's salted hash and iteration order."""
    import hashlib
    raw = "\0".join([str(seed), *(str(p) for p in parts)]).encode("utf-8")
    return random.Random(int.from_bytes(hashlib.sha256(raw).digest()[:8], "big"))

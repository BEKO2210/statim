def _pack(rows):
    """rows: list of 14-tuples in LANGUAGES order. Returns lang → list of strings."""
    out = {lang: [] for lang in LANGUAGES}
    for row in rows:
        if len(row) != len(LANGUAGES):
            raise ValueError("template row has %d languages, expected %d" % (len(row), len(LANGUAGES)))
        for lang, text in zip(LANGUAGES, row):
            if not str(text).strip():
                raise ValueError("empty template for %s" % lang)
            out[lang].append(str(text).strip())
    return out


def _gloss(rows):
    """rows: label → 14-tuple. Returns lang → label → description."""
    out = {lang: {} for lang in LANGUAGES}
    for label, texts in rows.items():
        if len(texts) != len(LANGUAGES):
            raise ValueError("gloss %s has %d languages" % (label, len(texts)))
        for lang, text in zip(LANGUAGES, texts):
            out[lang][label] = str(text).strip()
    return out


def _levels(rows):
    """rows: list of 14-tuples, one per level, same order in every language."""
    packed = _pack(rows)
    return packed


